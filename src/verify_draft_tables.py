"""Draft-vs-artifact gate for the flagship reproduction pipeline.

Regenerates the paper tables via actr_tables.run(check=True) and
exits nonzero unless every emitted cell matches its table block in
paper.md and the narrative DISCREPANCIES list is empty.
actr_tables' own CLI always exits 0 (its --check output is
informational); the pipeline needs the loud version - a reproduction
whose regenerated numbers diverge from the printed draft must fail the
run, not print a diff and continue. Runs after the actr_tables
stage, so the tables are already regenerated by the time it compares.
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import actr_tables


def main(argv=None):
    summary = actr_tables.run(check=True)
    check = summary.get("check", {})
    not_found = [f for f, t in check.get("per_table", {}).items()
                 if t.get("status") == "NOT FOUND"]
    ok, cells = check.get("total_ok", 0), check.get("total_cells", -1)
    failures = []
    if not_found:
        failures.append(f"draft block not found for {not_found}")
    if ok != cells or cells <= 0:
        failures.append(f"{ok}/{cells} cells match paper.md")
    if summary.get("discrepancies"):
        failures.append(f"narrative discrepancies: {summary['discrepancies']}")
    if failures:
        for f in failures:
            print(f"[verify_draft_tables] FAILED: {f}", file=sys.stderr)
        return 1
    print(f"[verify_draft_tables] OK: {ok}/{cells} cells match paper.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
